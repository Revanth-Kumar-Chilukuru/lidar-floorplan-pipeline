import os
import glob

AUTHOR_NAME = "Revanth Kumar Chilukuru"

# Update README
with open("README.md", "r", encoding="utf-8") as f:
    readme = f.read()

if "Author:" not in readme:
    readme = readme.replace("# Property Capture & Reconstruction Pipeline\n", 
    f"# Property Capture & Reconstruction Pipeline\n\n**Author:** {AUTHOR_NAME}\n\n## Process\nBuilt with AI coding assistance; see Technical Report section 7 for the development and remediation history.\n")
else:
    readme = readme.replace("Antigravity Engineering Candidate", AUTHOR_NAME)
    
with open("README.md", "w", encoding="utf-8") as f:
    f.write(readme)

# Update Technical Report
with open("TECHNICAL_REPORT.md", "r", encoding="utf-8") as f:
    tr = f.read()
tr = tr.replace("Antigravity Engineering Candidate", AUTHOR_NAME)
with open("TECHNICAL_REPORT.md", "w", encoding="utf-8") as f:
    f.write(tr)

# Go through python files and remove "generated by", add author header
py_files = glob.glob("src/**/*.py", recursive=True) + glob.glob("scripts/**/*.py", recursive=True) + ["main.py"]
for p in py_files:
    if "update_authorship" in p:
        continue
    with open(p, "r", encoding="utf-8") as f:
        content = f.read()
    
    lines = content.split('\n')
    new_lines = []
    has_author = False
    for line in lines:
        if "generated by" in line.lower() or "ai assistant" in line.lower() or "antigravity" in line.lower():
            continue
        if "Author:" in line:
            has_author = True
            line = f'Author: {AUTHOR_NAME}'
        new_lines.append(line)
    
    if not has_author:
        new_lines.insert(0, f'"""\nAuthor: {AUTHOR_NAME}\n"""')
        
    with open(p, "w", encoding="utf-8") as f:
        f.write('\n'.join(new_lines))
